defmodule VoxelRegion.ThermalFireBenchmarkTest do
  @moduledoc """
  Test-only benchmark: large fires through the real World thermal commit path, excluded by default.

  World = `GeneratedStore` over the Test-only emergent-loop world 4ecf1f7864707144 (manifest fixture copied from
  Voxim `Saved/Gameplay/emergent-loop-20260923/server/worldgen-manifest.json`; L0 is regenerated by the kernel into
  a reusable cache under the system temp dir), the radiation-tuned published catalog 5be2e8c7 and the Test-only
  radiation environment (eps 0.9, tolerance 1 K), the production `OverlayLog.Db` backend (Postgres at MMO_DB_PORT,
  a per-VM database), two gate-style log subscriptions and one scene-style canonical subscription over the demo
  scene box. Time advances only through the World's own `:thermal_commit` timer (natural cadence).

  Scenes (BENCH_SCENE, default `forest`):
  - `forest`: rad-loop-04 reproduced on the same generated terrain: the eleven gathered cells removed, the placed
    2x3 stone base and two wood blocks authored, then tool 9 (K) on the HOST wood (67,416,-514); the fire spreads
    through the generated spruce forest.
  - `house`: the 118-cell 7x4x7 wooden house of `fire_furnace_production_test` on a grass platform in open air.
  - `qinglan`: the forest fire plus three such houses ignited together (several simultaneous player fires).

  BENCH_SECONDS sets the simulated window (default 375 s, the rad-loop-04 observation window); BENCH_OUT an
  optional directory for the JSON summary. Reported: simulated/wall real-time ratio per 25 s window, per-commit
  handler time (capacity headroom = 0.5 s / handler time), the World's own stage timings (thermal rounds, burn-out
  geometry commits, checkpoints), kernel node/edge/radiation counts, kernel calls and rows per commit, World memory.
  BENCH_DIGEST=1 instead prints a state digest every 5 s of simulated time (before/after physics comparison);
  BENCH_PROFILE=<s> runs eprof on the World for 10 simulated seconds from that time (diagnosis only).

  `MMO_DB_PORT=5433 mix test --no-start --only benchmark test/thermal_fire_benchmark_test.exs` in apps/voxel_region.
  """
  use ExUnit.Case, async: false
  @moduletag :benchmark
  @moduletag timeout: :infinity
  alias VoxelRegion.World
  alias VoxelRegion.TestSupport.Actor
  import Bitwise

  @digest "5be2e8c79d8789a29aa17e023294c8aafbff51ff4b8c07a945035dbfcf91fe57"
  @fixtures Path.expand("fixtures", __DIR__)
  @grass 1
  @stone 11
  @coal 15
  @wood 19

  defmodule Capture do
    @moduledoc "Test-only logger handler: forwards the World's own thermal timing lines to the benchmark."
    def log(%{msg: {:string, text}}, %{config: %{pid: pid}}) do
      text = IO.chardata_to_string(text)
      if String.starts_with?(text, ["voxel_thermal", "voxel_macro_stages", "voxel_checkpoint ", "voxel_select_region",
          "voxel_region_afterimage"]),
        do: send(pid, {:bench, text})
      :ok
    end

    def log(_, _), do: :ok
  end

  # rad-loop-04 (Voxim Saved/Gameplay/emergent-loop-20260923/rad-loop-04): probe cells before -> after.
  @gathered [{71, 419, -517}, {71, 420, -517}, {71, 421, -517}, {67, 418, -519}, {66, 418, -519}, {67, 419, -520},
             {66, 417, -518}, {66, 419, -520}, {67, 417, -519}, {78, 413, -534}, {78, 412, -534}]
  @base for x <- 66..67, z <- -514..-512, do: {x, 415, z}
  @host {67, 416, -514}
  @placed_wood [{67, 416, -513}, @host]

  defp house_cells({ox, oy, oz}) do
    for x <- 0..6, y <- 1..4, z <- 0..6, x in [0, 6] or z in [0, 6] or y == 4,
        {x, y, z} not in [{3, 1, 0}, {3, 2, 0}, {6, 2, 3}],
        do: {ox + x, oy + y, oz + z}
  end

  defp platform({ox, oy, oz}), do: for(x <- -1..7, z <- -1..7, do: {ox + x, oy, oz + z})

  # Open air: the generated terrain under these footprints tops out at y 466.
  @houses [{100, 480, -524}, {120, 480, -524}, {140, 480, -524}]

  setup_all do
    MmoTest.Database.start!()
    :ok
  end

  setup do
    root = Path.join(System.tmp_dir!(), "thermal_bench_#{System.unique_integer([:positive])}")
    File.mkdir_p!(root)
    on_exit(fn -> File.rm_rf!(root) end)
    %{root: root}
  end

  defp start_world(c) do
    store = Path.join(System.tmp_dir!(), "thermal_bench_store")
    File.mkdir_p!(store)
    catalog = Path.join(c.root, "properties.json")
    File.cp!(Path.join([@fixtures, "combustion", @digest <> ".json"]), catalog)
    env = Path.join(c.root, "environment.json")
    File.cp!(Path.join([@fixtures, "combustion", "environment-radiation.json"]), env)
    # The world's overlay log lives in the per-VM test database; nothing is replayed from an earlier run.
    {:ok, _} = Ecto.Adapters.SQL.query(DataService.Repo, "DELETE FROM voxel_overlay_log", [])

    manifest = Path.join([@fixtures, "benchmark", "worldgen-manifest.json"])
    # Edits reduce into L1..L5: bake (kernel output, as the server's ready gate does) the coarse regions over the scenes.
    {:ok, generated} = VoxelRegion.GeneratedStore.open(root: store, manifest_path: manifest)
    # The server's ready gate also writes the L1..L5 column-bounds index (`VoxelRegion.Bake`); without it every
    # coarse read recomputes column bounds (seconds at L5), which a deployed World never does.
    generated = if generated.index, do: generated, else: VoxelRegion.GeneratedStore.write_index(%{generated | index:
      %{extent: generated.extent, bounds: for(level <- 1..5, column <- VoxelRegion.GeneratedStore.columns(generated, level),
        do: {level, column}) |> Task.async_stream(fn {level, {rx, rz}} -> {{level, rx, rz},
          VoxelRegion.Native.column_bounds(level, {rx, rz}, generated.config)} end, timeout: :infinity, ordered: false)
        |> Map.new(fn {:ok, entry} -> entry end)}})
    for level <- 1..5, {rx, ry, rz} <- scene_regions(level), dx <- -1..1, dy <- -1..1, dz <- -1..1,
        do: :ok = VoxelRegion.GeneratedStore.ensure(generated, level, {rx + dx, ry + dy, rz + dz}) |> baked(generated, level, {rx + dx, ry + dy, rz + dz})

    start_supervised!({World, [source: VoxelRegion.GeneratedStore, root: store, manifest_path: manifest,
      log: VoxelRegion.OverlayLog.Db, name: nil, property_catalog_path: catalog, thermal_environment_path: env,
      production_materials: [@coal]]})
  end

  defp baked({:error, :not_baked}, store, level, region), do: VoxelRegion.GeneratedStore.bake_region(store, level, region)
  defp baked(:ok, _, _, _), do: :ok

  defp scene_regions(level) do
    cells = [{45, 405, -540}, {90, 430, -490}] ++ Enum.flat_map(@houses, fn {x, y, z} -> [{x - 1, y, z - 1}, {x + 7, y + 4, z + 7}] end)
    Enum.uniq(for {x, y, z} <- cells, do: {Integer.floor_div(x >>> level, 64), Integer.floor_div(y >>> level, 64), Integer.floor_div(z >>> level, 64)})
  end

  defp actor(eye) do
    a = %{cid: 1001, gate: self(), identity: make_ref(), refresh: &Actor.tool_context/2, eye: eye, tick_us: 16_667}
    Map.put(a, :player, start_supervised!({Actor, a}, id: make_ref()))
  end

  defp ignite(w, eye, direction, seq, expected) do
    a = actor(eye)
    q = %{request_id: seq, client_intent_seq: seq, logical_scene_id: 1, action: 0, tool_id: 9, direction: direction,
      micro: {0, 0, 0}, granularity: 0, incarnation: 0, owner: {0, 0}, material: 0}
    {:ok, t} = World.tool_intent(w, a, q)
    assert t.micro == expected |> Tuple.to_list() |> Enum.map(&(&1 * 8)) |> List.to_tuple()
    r = Map.merge(q, Map.take(t, [:micro, :granularity, :incarnation, :owner, :material])) |> Map.put(:action, 1)
    {:ok, _} = World.tool_intent(w, Map.merge(a, %{received_us: seq * 1_000_000, clock_node: node()}), r)
  end

  defp occupancy(w, cells) do
    snapshot = World.material_snapshot(w, [], cells)
    Map.new(snapshot.probe_occupancy, &{List.to_tuple(&1.cell), &1.material})
  end

  defp forest(w) do
    before = occupancy(w, @gathered ++ @base ++ @placed_wood)
    assert Enum.map(@gathered, &before[&1]) == [@wood, @wood, @wood | List.duplicate(@stone, 7)] ++ [@coal]
    assert Enum.all?(@base ++ @placed_wood, &(before[&1] == 0))
    {:ok, _} = World.apply_edits(w, Enum.map(@gathered, &{&1, 0}) ++ Enum.map(@base, &{&1, @stone}) ++
      Enum.map(@placed_wood, &{&1, @wood}))
    ignite(w, {67.5, 418.5, -513.5}, {0.0, -1.0, 0.0}, 1, @host)
  end

  defp house(w, {ox, oy, oz} = origin, seq) do
    cells = house_cells(origin)
    assert Enum.all?(occupancy(w, platform(origin) ++ cells), fn {_, m} -> m == 0 end)
    {:ok, _} = World.apply_edits(w, Enum.map(platform(origin), &{&1, @grass}) ++ Enum.map(cells, &{&1, @wood}))
    ignite(w, {ox + 6.5, oy + 1.5, oz - 4.0}, {0.0, 0.0, 1.0}, seq, {ox + 6, oy + 1, oz})
  end

  defp subscribe(w) do
    drain = spawn_link(fn -> drain() end)
    for _ <- 1..2, do: :ok = World.subscribe(w, spawn_link(fn -> drain() end), 0, {{-1, 5, -10}, {2, 7, -7}}, 0)
    :ok = World.canonical_snapshot_and_subscribe(w, {{0, 6, -9}, {2, 8, -7}}, drain, make_ref())
  end

  defp drain do
    receive do
      _ -> drain()
    end
  end

  defp fields(text) do
    [name | pairs] = String.split(text, " ")
    {name, Map.new(for pair <- pairs, [k, v] <- [String.split(pair, "=", parts: 2)], do: {k, number(v)})}
  end

  defp number(v) do
    case Float.parse(v) do
      {f, ""} -> f
      _ -> v
    end
  end

  # One commit record per `voxel_thermal_callback`: the kernel/prepare lines before it belong to it.
  defp collect(w, target, started, acc) do
    receive do
      {:bench, text} ->
        now = System.monotonic_time(:microsecond)
        {name, f} = fields(text)
        acc =
          case name do
            "voxel_thermal_kernel" -> update_in(acc.pending.kernel, &[f | &1])
            "voxel_thermal_prepare" -> update_in(acc.pending.prepare, &[f | &1])
            "voxel_thermal_sim" -> put_in(acc.pending.sim, f)
            "voxel_thermal_commit" -> put_in(acc.pending.commit, f)
            "voxel_macro_stages" -> put_in(acc.pending.geometry, f)
            "voxel_checkpoint" -> update_in(acc.checkpoints, &[f["elapsed_us"] | &1])
            # Burn-out geometry commits: region selection / after-image encoding cost per level.
            region when region in ["voxel_select_region", "voxel_region_afterimage"] ->
              key = {region, f["level"], f["region_bytes"] != nil and f["region_bytes"] > 0}
              update_in(acc.regions, &Map.update(&1, key, {1, f["elapsed_us"]}, fn {n, us} -> {n + 1, us + f["elapsed_us"]} end))
            "voxel_thermal_callback" ->
              record = Map.merge(acc.pending, %{callback_us: f["elapsed_us"], at_us: now - started, sim_s: f["sim_s"],
                transform_us: f["transform_us"]})
              acc = %{acc | commits: [record | acc.commits], pending: pending()}
              if acc.memory == [] or now - started - hd(acc.memory).at_us > 5_000_000,
                do: update_in(acc.memory, &[memory(w, now - started) | &1]),
                else: acc
            _ -> acc
          end

        sim = acc.commits |> List.first() |> then(&(&1 && &1.sim_s))
        acc = profile(w, sim, acc)
        if is_number(sim) and sim >= target, do: acc, else: collect(w, target, started, acc)
    after
      # The fire settled before the window ended: no more active commits.
      30_000 -> acc
    end
  end

  # BENCH_PROFILE=<sim s>: eprof on the World process for the next 20 commits (Test-only diagnosis, not a metric).
  defp profile(w, sim, acc) do
    at = System.get_env("BENCH_PROFILE")
    cond do
      at == nil or not is_number(sim) -> acc
      acc[:profiling] == nil and sim >= String.to_integer(at) ->
        Mix.ensure_application!(:tools)
        :eprof.start()
        :profiling = :eprof.start_profiling([w])
        Map.put(acc, :profiling, sim)
      is_number(acc[:profiling]) and sim >= acc.profiling + 10 ->
        :eprof.stop_profiling()
        File.mkdir_p!(System.get_env("BENCH_OUT", System.tmp_dir!()))
        :eprof.log(to_charlist(Path.join(System.get_env("BENCH_OUT", System.tmp_dir!()), "eprof.txt")))
        :eprof.analyze(:total, sort: :time)
        :eprof.stop()
        Map.put(acc, :profiling, :done)
      true -> acc
    end
  end

  defp memory(w, at_us) do
    {:memory, memory} = Process.info(w, :memory)
    {:message_queue_len, queue} = Process.info(w, :message_queue_len)
    %{at_us: at_us, world_bytes: memory, queue: queue, vm_bytes: :erlang.memory(:total)}
  end

  defp pending, do: %{kernel: [], prepare: [], sim: nil, commit: nil, geometry: nil}

  defp percentile(values, p) do
    sorted = Enum.sort(values)
    Enum.at(sorted, min(length(sorted) - 1, trunc(p * length(sorted))))
  end

  defp geometry_us(f),
    do: Enum.sum(for k <- ~w(reduce_us l0_cache_us structure_us regions_us collision_us log_us fanout_us), do: f[k] || 0)

  defp sum(list, key), do: Enum.reduce(list, 0, &(&2 + (Map.get(&1, key) || 0)))

  defp summarize(scene, commits, memory, checkpoints) do
    # A commit that removes burnt-out cells is a geometry transaction without a `voxel_thermal_commit` line.
    commits = Enum.reverse(commits) |> Enum.filter(& &1.sim)
    windows =
      commits
      |> Enum.chunk_by(&trunc(&1.sim_s / 25))
      |> Enum.map(fn group ->
        first = hd(group)
        last = List.last(group)
        kernel = Enum.flat_map(group, & &1.kernel)
        prepare = Enum.flat_map(group, & &1.prepare)
        n = length(group)
        wall = (last.at_us - first.at_us) / 1.0e6
        %{
          sim_to: last.sim_s,
          ratio: if(wall > 0, do: (last.sim_s - first.sim_s) / wall, else: nil),
          commits: n,
          callback_ms_mean: sum(group, :callback_us) / n / 1000,
          callback_ms_p95: percentile(Enum.map(group, & &1.callback_us), 0.95) / 1000,
          sim_ms: Enum.reduce(group, 0, &(&2 + &1.sim["elapsed_us"])) / n / 1000,
          geometry_ms: Enum.reduce(group, 0, &(&2 + ((&1.geometry && geometry_us(&1.geometry)) || 0))) / n / 1000,
          # Mean stage times of the burn-out (geometry) commits alone.
          geometry_stages: (for c <- group, c.geometry, reduce: %{} do
            acc -> Enum.reduce(~w(reduce_us l0_cache_us structure_us regions_us collision_us log_us fanout_us), acc,
              fn k, acc -> Map.update(acc, k, [c.geometry[k] || 0], &[c.geometry[k] || 0 | &1]) end)
          end) |> Map.new(fn {k, v} -> {k, Float.round(Enum.sum(v) / length(v) / 1000, 1)} end),
          nif_calls: length(kernel) / n,
          nodes_max: kernel |> Enum.map(& &1["nodes"]) |> Enum.max(fn -> 0 end),
          edges_max: kernel |> Enum.map(& &1["edges"]) |> Enum.max(fn -> 0 end),
          pairs_max: kernel |> Enum.map(& &1["radiation_pairs"]) |> Enum.max(fn -> 0 end),
          sky_max: kernel |> Enum.map(& &1["sky_faces"]) |> Enum.max(fn -> 0 end),
          hot_max: group |> Enum.map(& &1.sim["hot"]) |> Enum.max(),
          states_mean: Enum.reduce(group, 0, &(&2 + ((&1.commit && &1.commit["states"]) || 0))) / n,
          geometry_commits: Enum.count(group, &(&1.commit == nil)),
          ms: %{
            neighborhood: sum(prepare, "neighborhood_us") / n / 1000,
            geometry: sum(prepare, "geometry_us") / n / 1000,
            nodes: sum(prepare, "nodes_us") / n / 1000,
            input: sum(prepare, "input_us") / n / 1000,
            refresh: sum(prepare, "refresh_us") / n / 1000,
            rebuild: sum(prepare, "rebuild_us") / n / 1000,
            terms: sum(prepare, "terms_us") / n / 1000,
            samples: sum(prepare, "samples_us") / n / 1000,
            batch: sum(prepare, "batch_us") / n / 1000,
            settle: sum(prepare, "settle_us") / n / 1000,
            merge: sum(prepare, "merge_us") / n / 1000,
            ignite: sum(prepare, "ignite_us") / n / 1000,
            rebuilds: Enum.count(prepare, &(&1["rebuild"] == "true")) / n,
            nif: sum(kernel, "nif_us") / n / 1000,
            accept: sum(kernel, "accept_us") / n / 1000,
            steps: Enum.reduce(group, 0, &(&2 + (&1.sim["steps_us"] || 0))) / n / 1000,
            scan: Enum.reduce(group, 0, &(&2 + (&1.sim["scan_us"] || 0))) / n / 1000,
            transform: Enum.reduce(group, 0, &(&2 + (&1[:transform_us] || 0))) / n / 1000,
            persist: Enum.reduce(group, 0, &(&2 + ((&1.commit && &1.commit["persist_us"]) || 0))) / n / 1000,
            broadcast: Enum.reduce(group, 0, &(&2 + ((&1.commit && &1.commit["broadcast_us"]) || 0))) / n / 1000
          }
        }
      end)

    total_wall = (List.last(commits).at_us - hd(commits).at_us) / 1.0e6
    total_sim = List.last(commits).sim_s - hd(commits).sim_s
    handler = sum(commits, :callback_us) / 1.0e6

    summary = %{
      scene: scene,
      commits: length(commits),
      sim_s: total_sim,
      wall_s: total_wall,
      ratio: total_sim / total_wall,
      handler_s: handler,
      capacity: 0.5 * length(commits) / handler,
      callback_ms_p50: percentile(Enum.map(commits, & &1.callback_us), 0.5) / 1000,
      callback_ms_p95: percentile(Enum.map(commits, & &1.callback_us), 0.95) / 1000,
      callback_ms_max: Enum.max(Enum.map(commits, & &1.callback_us)) / 1000,
      world_mb_max: Enum.max(Enum.map(memory, & &1.world_bytes), fn -> 0 end) / 1.0e6,
      checkpoint_ms: Enum.map(Enum.reverse(checkpoints), &(&1 / 1000)),
      slowest: commits |> Enum.sort_by(& &1.callback_us, :desc) |> Enum.take(5)
        |> Enum.map(&%{sim_s: &1.sim_s, callback_ms: &1.callback_us / 1000, sim_ms: &1.sim["elapsed_us"] / 1000,
          nif_calls: length(&1.kernel), geometry: &1.geometry}),
      vm_mb_max: Enum.max(Enum.map(memory, & &1.vm_bytes), fn -> 0 end) / 1.0e6,
      memory: Enum.reverse(memory),
      windows: windows
    }

    IO.puts("THERMAL_BENCH scene=#{scene} commits=#{summary.commits} sim_s=#{Float.round(total_sim, 1)} " <>
      "wall_s=#{Float.round(total_wall, 1)} ratio=#{Float.round(summary.ratio, 3)} capacity=#{Float.round(summary.capacity, 2)} " <>
      "callback_ms p50=#{summary.callback_ms_p50} p95=#{summary.callback_ms_p95} max=#{summary.callback_ms_max} " <>
      "world_mb_max=#{Float.round(summary.world_mb_max, 1)} vm_mb_max=#{Float.round(summary.vm_mb_max, 1)} " <>
      "checkpoint_ms=#{inspect(summary.checkpoint_ms)}")
    for c <- summary.slowest, do: IO.puts("  slow #{inspect(c)}")

    for w <- windows do
      IO.puts("  sim<=#{Float.round(w.sim_to, 1)} ratio=#{w.ratio && Float.round(w.ratio, 3)} cb_ms=#{Float.round(w.callback_ms_mean, 1)}/" <>
        "#{Float.round(w.callback_ms_p95 * 1.0, 1)} sim_ms=#{Float.round(w.sim_ms, 1)} geo_ms=#{Float.round(w.geometry_ms * 1.0, 1)} nif_calls=#{Float.round(w.nif_calls, 1)} " <>
        "nodes=#{w.nodes_max} edges=#{w.edges_max} pairs=#{w.pairs_max} " <>
        "sky=#{w.sky_max} hot=#{w.hot_max} rows=#{Float.round(w.states_mean * 1.0, 0)} geo=#{w.geometry_commits} ms=" <>
        Enum.map_join(w.ms, ",", fn {k, v} -> "#{k}:#{Float.round(v * 1.0, 1)}" end) <>
        if(w.geometry_stages == %{}, do: "", else: " geo_stages=" <> Enum.map_join(w.geometry_stages, ",", fn {k, v} -> "#{k}#{v}" end)))
    end

    if out = System.get_env("BENCH_OUT") do
      File.mkdir_p!(out)
      File.write!(Path.join(out, "#{scene}.json"), Jason.encode!(summary, pretty: true))
    end

    summary
  end

  defp run(c, scene) do
    target = String.to_integer(System.get_env("BENCH_SECONDS", "375")) * 1.0
    w = start_world(c)
    {:ok, _} = World.material_supply(w, 1001, "fixture", %{@coal => 10_000_000})
    subscribe(w)

    Logger.configure(level: :info)
    :ok = :logger.set_handler_config(:default, :level, :warning)
    :ok = :logger.add_handler(:thermal_bench, Capture, %{level: :info, config: %{pid: self()}})

    try do
      case scene do
        "forest" -> forest(w)
        "house" -> house(w, hd(@houses), 1)
        "qinglan" ->
          forest(w)
          for {origin, i} <- Enum.with_index(@houses), do: house(w, origin, i + 2)
      end

      if System.get_env("BENCH_DIGEST"), do: digests(w, target), else: measure(w, scene, target)
    after
      :logger.remove_handler(:thermal_bench)
      :logger.set_handler_config(:default, :level, :all)
      Logger.configure(level: :warning)
    end
  end

  # BENCH_DIGEST=1: equivalence mode on the natural cadence. Right after each active commit's callback line the
  # World is idle until its next timer, so a snapshot then sees exactly that commit; every 5 s of simulated time
  # the whole property state and energy ledger is hashed for before/after comparison.
  defp digests(w, target) do
    receive do
      {:bench, "voxel_thermal_callback" <> _} ->
        s = GenServer.call(w, {:simulation_snapshot, [], {{-100, -100, -100}, {300, 600, 100}}}, :infinity)
        elapsed = s.thermal_accounting.elapsed_s
        if rem(trunc(elapsed * 2), 10) == 0 do
          rows = s.property_states |> Enum.map(fn t -> {VoxelRegion.Damage.key(t), Map.get(t, :temperature_kelvin), t.hp,
            Map.get(t, :remaining_fuel_j), Map.get(t, :burning)} end) |> Enum.sort()
          hash = :crypto.hash(:sha256, :erlang.term_to_binary({rows, s.thermal_accounting |> Enum.sort()}))
          IO.puts("THERMAL_DIGEST #{inspect(elapsed)} rows=#{length(rows)} #{Base.encode16(hash, case: :lower)}")
        end
        if elapsed < target, do: digests(w, target)

      {:bench, _} ->
        digests(w, target)
    end
  end

  defp measure(w, scene, target) do
      started = System.monotonic_time(:microsecond)
      acc = collect(w, target, started, %{commits: [], pending: pending(), memory: [], checkpoints: [], regions: %{}})
      for {{name, level, encoded}, {n, us}} <- Enum.sort(acc.regions),
        do: IO.puts("  #{name} level=#{inspect(level)} full_region=#{encoded} count=#{n} total_ms=#{Float.round(us / 1000, 1)}")
      summary = summarize(scene, acc.commits, acc.memory, acc.checkpoints)
      # Live World heap by state field at the end of the window (words shared inside a field counted once).
      state = :sys.get_state(w)
      words = :erlang.system_info(:wordsize)
